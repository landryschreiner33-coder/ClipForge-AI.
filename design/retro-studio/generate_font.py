builder = FontBuilder(1000, isTTF=True)
order = ['.notdef', 'space'] + [f'g{ord(c)}' for c in PATTERNS]
builder.setupGlyphOrder(order)
glyphs, metrics = {}, {}
for name in order:
    pen = TTGlyphPen(None)
    char = next((c for c in PATTERNS if name == f'g{ord(c)}'), None)
    rows = PATTERNS[char] if char else []
    for row, bits in enumerate(rows):
        for col, bit in enumerate(bits):
            if bit == '1':
                x, y = col * 100 + 50, (6 - row) * 100
                pen.moveTo((x, y)); pen.lineTo((x, y + 100))
                pen.lineTo((x + 100, y + 100)); pen.lineTo((x + 100, y)); pen.closePath()
    glyphs[name] = pen.glyph()
    metrics[name] = ((len(rows[0]) + 1) * 100 if rows else 400, 50)
charmap = {ord(c): f'g{ord(c)}' for c in PATTERNS}
charmap.update({ord(c.lower()): f'g{ord(c)}' for c in PATTERNS if c.isalpha()})
charmap[32] = 'space'
builder.setupCharacterMap(charmap)
builder.setupGlyf(glyphs)
builder.setupHorizontalMetrics(metrics)
builder.setupHorizontalHeader(ascent=850, descent=-150)
builder.setupNameTable({'familyName':'Foundry Pixel','styleName':'Regular','uniqueFontIdentifier':'ClipFoundry Foundry Pixel 1',
                        'fullName':'Foundry Pixel','psName':'FoundryPixel','version':'Version 1.0',
                        'copyright':'Original artwork for ClipFoundry. All rights reserved.'})
builder.setupOS2(sTypoAscender=850, sTypoDescender=-150, usWinAscent=850, usWinDescent=150)
builder.setupPost()
builder.setupMaxp()
builder.save(Path(__file__).resolve().parents[2] / 'frontend/src/assets/foundry-pixel.ttf')
